def _split_script(script: str) -> Iterator[str]:
    """Split a multi-statement script on ``;`` while respecting ``$$``-quoted
    function bodies (PL/pgSQL), single-quoted strings, ``--`` line comments
    and ``/* */`` block comments."""
    parts: list[str] = []
    current: list[str] = []
    in_dollar = False
    in_string = False
    in_line_comment = False
    in_block_comment = False
    i = 0
    while i < len(script):
        ch = script[i]
        nxt = script[i : i + 2]
        if in_line_comment:
            current.append(ch)
            if ch == "\n":
                in_line_comment = False
        elif in_block_comment:
            current.append(ch)
            if nxt == "*/":
                current.append("/")
                in_block_comment = False
                i += 1
        elif in_dollar:
            current.append(ch)
            if nxt == "$$":
                current.append("$")
                in_dollar = False
                i += 1
        elif in_string:
            current.append(ch)
            if ch == "'":
                in_string = False
        else:
            if nxt == "--":
                in_line_comment = True
                current.append(ch)
            elif nxt == "/*":
                in_block_comment = True
                current.append(ch)
            elif nxt == "$$":
                in_dollar = True
                current.append(ch)
                current.append("$")
                i += 1
            elif ch == "'":
                in_string = True
                current.append(ch)
            elif ch == ";":
                statement = "".join(current).strip()
                if statement:
                    parts.append(statement)
                current = []
            else:
                current.append(ch)
        i += 1
    tail = "".join(current).strip()
    if tail:
        parts.append(tail)
    return iter(parts)


class PgRow(dict):
    """``sqlite3.Row``-compatible row: name access, positional access and
    value-order unpacking (``for a, b in row`` yields values, not keys).

    ``dict(row)`` still produces ``{column: value}`` because the row *is* a
    dict; the positional view is materialised once at construction.
    """

    __slots__ = ("_values",)

    def __init__(
        self, values: dict[str, Any], ordered: Sequence[Any] | None = None
    ) -> None:
        super().__init__(values)
        # Unnamed expressions share a column name (e.g. several COALESCE(...)
        # columns all named "coalesce"); the dict collapses duplicates, so the
        # positional view must come from the raw value sequence.
        self._values = list(ordered) if ordered is not None else list(values.values())

    def __getitem__(self, key: Any) -> Any:
        if isinstance(key, (int, slice)):
            return self._values[key]
        return super().__getitem__(key)

    def __iter__(self) -> Iterator[Any]:
        return iter(self._values)


def _pg_row_factory(cursor: Any) -> Any:
    description = cursor.description
    if description is None:
        # Statements without a result set (DDL, DML without RETURNING) still
        # ask for a factory — return raw tuples for the (empty) results.
        return tuple
    names = [column.name for column in description]

    def make_row(values: Sequence[Any]) -> PgRow:
        return PgRow(dict(zip(names, values)), ordered=values)

    return make_row


class PgCursor:
    """Minimal cursor surface: fetchone/fetchall/fetchmany/rowcount.

    Rows behave like ``sqlite3.Row``: index, name and ``keys()`` access,
    plus value-order unpacking, via :class:`PgRow`.
    """

    def __init__(self, cursor: Any, pk_resolver: Any = None) -> None:
        self._cursor = cursor
        self._pk_resolver = pk_resolver

    def __iter__(self) -> Iterator[Any]:
        return iter(self._cursor)

    def fetchone(self) -> Any:
        return self._cursor.fetchone()

    def fetchall(self) -> list[Any]:
        return self._cursor.fetchall()

    def fetchmany(self, size: int) -> list[Any]:
        return self._cursor.fetchmany(size)

    @property
    def rowcount(self) -> int:
        return self._cursor.rowcount

    @property
    def lastrowid(self) -> Any:
        return getattr(self._cursor, "lastrowid", None)

    def close(self) -> None:
        self._cursor.close()

    def execute(self, statement: str, parameters: Sequence[Any] = ()) -> "PgCursor":
        translated = translate(statement, pk_resolver=self._pk_resolver)
        if not translated:
            return self
        self._cursor.execute(translated, parameters)
        return self

    def executemany(self, statement: str, seq: Iterable[Sequence[Any]]) -> "PgCursor":
        translated = translate(statement, pk_resolver=self._pk_resolver)
        if not translated:
            return self
        self._cursor.executemany(translated, list(seq))
        return self


class PgConnection:
    """sqlite3.Connection-compatible facade over a psycopg connection."""

    def __init__(
        self,
        connection: Any,
        schema: str,
        pool_key: tuple[Any, ...] | None = None,
    ) -> None:
        self._connection = connection
        self.schema = schema
        self.row_factory: Any = None  # accepted for API parity; rows are dicts
        self._pk_cache: dict[str, list[str] | None] = {}
        self._pool_key = pool_key

    def _resolve_pk(self, table: str) -> list[str] | None:
        """Return the primary-key column list for *table* in search_path.

        Cached per connection; ``None`` (cached) means the table has no
        primary key — callers then fall back to the first INSERT column.
        """
        if table in self._pk_cache:
            return self._pk_cache[table]
        row_cur = self._connection.cursor()
        row_cur.execute(
            "SELECT kcu.column_name FROM information_schema.table_constraints tc "
            "JOIN information_schema.key_column_usage kcu "
            "ON tc.constraint_schema = kcu.constraint_schema "
            "AND tc.constraint_name = kcu.constraint_name "
            "WHERE tc.constraint_type = 'PRIMARY KEY' "
            "AND tc.table_schema = current_schema() AND tc.table_name = %s "
            "ORDER BY kcu.ordinal_position",
            (table,),
        )
        cols = [str(r[0]) for r in row_cur.fetchall()]
        row_cur.close()
        self._pk_cache[table] = cols or None
        return self._pk_cache[table]

    # -- sqlite3 surface ------------------------------------------------------

    def execute(self, statement: str, parameters: Sequence[Any] = ()) -> PgCursor:
        cur = self.cursor()
        return cur.execute(statement, parameters)

    def executemany(self, statement: str, seq: Iterable[Sequence[Any]]) -> PgCursor:
        cur = self.cursor()
        return cur.executemany(statement, seq)

    def executescript(self, script: str) -> PgCursor:
        cur = self.cursor()
        for statement in _split_script(script):
            cur.execute(statement)  # sql-ok: executescript parity — bounded split of caller-owned DDL script
        return cur

    def cursor(self) -> PgCursor:
        return PgCursor(self._connection.cursor(), pk_resolver=self._resolve_pk)

    def commit(self) -> None:
        self._connection.commit()

    def rollback(self) -> None:
        self._connection.rollback()

    def close(self) -> None:
        connection = self._connection
        if connection is None:
            return
        self._connection = None
        if self._pool_key is not None and _pool_enabled():
            _pool_release(self._pool_key, connection)
        else:
            connection.close()

    @property
    def total_changes(self) -> int:
        return 0  # informational only in sqlite; not required by callers

    # -- context manager: sqlite3 semantics = commit on success ---------------

    def __enter__(self) -> "PgConnection":
        return self

    def __exit__(self, exc_type, exc, tb) -> bool:
        if self._connection is None:
            return False
        if exc_type is None:
            self._connection.commit()
        else:
            self._connection.rollback()
        self.close()  # return the backend to the pool on block exit
        return False


