"""pg_adapter — PostgreSQL-backed drop-in for ``sqlite3`` call sites.

A8/A503/A610/A621: PostgreSQL is the sole structured-data authority;
SQLite is retired.  This module gives legacy ``sqlite3.connect(...)``
call sites a minimal migration surface so each store can move to
PostgreSQL without rewriting its query layer:

    # before
    connection = sqlite3.connect(path, isolation_level=None)
    connection.row_factory = sqlite3.Row
    # after
    connection = pg_adapter.connect(schema="gptbridge_mod_xingcheng")

Supported surface (what the governed stores actually use):

* ``connect(...)`` -> :class:`PgConnection` with ``execute``,
  ``executemany``, ``executescript``, ``commit``, ``rollback``,
  ``close``, context-manager protocol and ``row_factory``-style dict
  rows (``cursor.description`` named access).
* Statement translation: ``?`` -> ``%s``, ``INSERT OR REPLACE`` ->
  ``INSERT ... ON CONFLICT DO UPDATE`` (column list preserved, conflict
  target = the table's primary key), ``INSERT OR IGNORE`` ->
  ``ON CONFLICT DO NOTHING``, ``REPLACE INTO`` -> upsert,
  ``BEGIN IMMEDIATE``/``BEGIN DEFERRED`` -> ``BEGIN``,
  ``sqlite_master`` -> ``information_schema``, ``PRAGMA`` -> no-op
  (``journal_mode``/``synchronous``/``foreign_keys`` etc. — PG
  equivalents are server-side or already enforced), ``datetime('now')``
  -> ``now()``, ``AUTOINCREMENT``/``INTEGER PRIMARY KEY`` ->
  ``GENERATED BY DEFAULT AS IDENTITY``.
* Fail-closed: no DSN -> :class:`PgUnavailable` (never a silent local
  file fallback — that was the sqlite anti-pattern this removes).

NOT a general SQL transpiler — it covers the governed store surface;
callers that exercise exotic sqlite-isms must translate explicitly.
"""

from __future__ import annotations

import logging
import os
import re
import threading
from collections import OrderedDict
from typing import Any, Iterable, Iterator, Sequence

_logger = logging.getLogger("gptbridge.pg_adapter")


# ---------------------------------------------------------------------------
# Bounded connection pool
#
# ``psycopg.connect`` pays a full TCP + auth handshake + SET search_path on
# every call; the governed repositories open a connection per operation, so
# per-request latency was dominated by connect churn and each checkout also
# spawned a short-lived PG backend (server-side RAM/CPU).  A bounded pool
# keyed by (dsn, schema, autocommit, row_factory) turns each checkout into a
# single loopback ``SELECT 1`` validation (~100x cheaper than a handshake)
# while never mixing distinct bindings.
#
# ``PG_ADAPTER_POOL=0`` disables pooling outright (fail-open to the
# per-call-connect behaviour); a dead checked-out connection is discarded
# and a fresh one opened — callers never observe a broken pool entry.
# ---------------------------------------------------------------------------

_POOL_MAX_SIZE = 4
_pool_lock = threading.Lock()
_pool: dict[tuple[Any, ...], list[Any]] = {}


def _pool_enabled() -> bool:
    return os.environ.get("PG_ADAPTER_POOL", "1") != "0"


def _pool_checkout(key: tuple[Any, ...]) -> Any | None:
    while True:
        with _pool_lock:
            entries = _pool.get(key)
            conn = entries.pop() if entries else None
        if conn is None:
            return None
        try:
            conn.execute("SELECT 1")  # loopback liveness probe
        except Exception:
            try:
                conn.close()
            except Exception:
                pass
            continue
        return conn


def _pool_release(key: tuple[Any, ...], conn: Any) -> None:
    try:
        conn.rollback()  # no-op on clean/autocommit backends
    except Exception:
        pass
    try:
        if conn.closed:
            return
    except Exception:
        return
    with _pool_lock:
        entries = _pool.setdefault(key, [])
        if len(entries) < _POOL_MAX_SIZE:
            entries.append(conn)
            conn = None
    if conn is not None:
        try:
            conn.close()
        except Exception:
            pass


def close_pool() -> None:
    """Drop every pooled backend (process teardown / test isolation)."""
    with _pool_lock:
        entries = [conn for conns in _pool.values() for conn in conns]
        _pool.clear()
    for conn in entries:
        try:
            conn.close()
        except Exception:
            pass


class PgUnavailable(RuntimeError):
    """Raised when no governed PostgreSQL DSN is resolvable."""


# ---------------------------------------------------------------------------
# Statement translation
# ---------------------------------------------------------------------------

_PRAGMA_RE = re.compile(r"^\s*PRAGMA\b", re.IGNORECASE)
_PRAGMA_TABLE_INFO_RE = re.compile(
    r"^\s*PRAGMA\s+table_info\s*\(\s*['\"]?([A-Za-z_][\w$]*)['\"]?\s*\)\s*;?\s*$",
    re.IGNORECASE,
)
_SQLITE_MASTER_RE = re.compile(
    r"SELECT\s+name\s+FROM\s+sqlite_master\s+WHERE\s+type\s*=\s*'table'"
    r"(?:\s+AND\s+name\s*=\s*'([^']*)')?",
    re.IGNORECASE,
)
_BEGIN_RE = re.compile(r"^\s*BEGIN\s+(IMMEDIATE|DEFERRED|EXCLUSIVE)\s*;?\s*$", re.IGNORECASE)
_INSERT_OR_RE = re.compile(r"^\s*INSERT\s+OR\s+(REPLACE|IGNORE)\s+INTO\b", re.IGNORECASE)
_REPLACE_INTO_RE = re.compile(r"^\s*REPLACE\s+INTO\b", re.IGNORECASE)
_DATETIME_NOW_RE = re.compile(r"datetime\s*\(\s*'now'\s*\)", re.IGNORECASE)
_STRFTIME_NOW_RE = re.compile(
    r"strftime\s*\(\s*'%(.*?)'\s*,\s*'now'\s*\)", re.IGNORECASE
)
_INTEGER_PK_RE = re.compile(
    r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT", re.IGNORECASE
)

# Statement translation runs ~15 regex passes per query; the same
# statement texts recur constantly in the governed repositories, so cache
# translations that are pk_resolver-independent (only the INSERT OR
# REPLACE / REPLACE INTO conflict-clause path consults the resolver).
_translate_lock = threading.Lock()
_translate_cache: "OrderedDict[str, str]" = OrderedDict()
_TRANSLATE_CACHE_MAX = 1024


def translate(statement: str, pk_resolver: Any = None) -> str:
    """Translate a sqlite-flavoured statement into PostgreSQL syntax.

    ``PRAGMA`` returns an empty string (caller treats as no-op).
    ``?`` placeholders become ``%s`` (psycopg).  Literal ``%`` that is
    not part of a psycopg placeholder is escaped first.

    *pk_resolver* (optional) maps a table name to its primary-key column
    list; used to build the correct ``ON CONFLICT`` target for
    ``INSERT OR REPLACE`` on composite keys.
    """
    with _translate_lock:
        cached = _translate_cache.get(statement)
        if cached is not None:
            _translate_cache.move_to_end(statement)
            return cached
    stmt = statement.strip()
    pragma_info = _PRAGMA_TABLE_INFO_RE.match(stmt)
    if pragma_info:
        table = pragma_info.group(1).replace('"', '""')
        return (
            "SELECT ordinal_position - 1 AS cid, column_name AS name, "
            "data_type AS type, "
            "CASE WHEN is_nullable = 'NO' THEN 1 ELSE 0 END AS \"notnull\", "
            "column_default AS dflt_value, 0 AS pk "
            "FROM information_schema.columns "
            f"WHERE table_schema = current_schema() AND table_name = '{table}' "  # sql-ok: identifier validated by _PRAGMA_TABLE_INFO_RE charset
            "ORDER BY ordinal_position"
        )
    if _PRAGMA_RE.match(stmt):
        return ""
    if _BEGIN_RE.match(stmt):
        return "BEGIN"
    stmt = _SQLITE_MASTER_RE.sub(
        lambda m: (
            "SELECT table_name AS name FROM information_schema.tables "
            "WHERE table_type='BASE TABLE'"
            + (
                f" AND table_name='{m.group(1)}'"
                if m.group(1) is not None
                else ""
            )
        ),
        stmt,
    )
    stmt = _DATETIME_NOW_RE.sub("now()", stmt)
    # COLLATE NOCASE: sqlite's case-insensitive collation has no direct
    # PG builtin — drop it inside CREATE TABLE (case-sensitive key, as in
    # the migrated schemas) and lower() the operand in query expressions.
    if re.match(r"\s*CREATE\s+TABLE", stmt, re.IGNORECASE):
        stmt = re.sub(r"\s+COLLATE\s+NOCASE", "", stmt, flags=re.IGNORECASE)
    else:
        stmt = re.sub(
            r"([A-Za-z_][\w.]*)\s+COLLATE\s+NOCASE",
            r"lower(\1)",
            stmt,
            flags=re.IGNORECASE,
        )
    # sqlite LIKE is ASCII case-insensitive; ILIKE is the faithful match.
    stmt = re.sub(
        r"\bLIKE\b(?=\s+(?:\?|'|\())", "ILIKE", stmt, flags=re.IGNORECASE
    )
    # sqlite idiom: LIMIT -1 means "no bound" (usually with OFFSET).
    stmt = re.sub(r"\bLIMIT\s+-1\b", "LIMIT ALL", stmt, flags=re.IGNORECASE)
    # strftime('%Y-%m-%dT%H:%M:%SZ','now') keeps its ISO-8601 text shape;
    # any other format degrades to now() (timestamp).
    stmt = _STRFTIME_NOW_RE.sub(
        lambda m: (
            "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD\"T\"HH24:MI:SS\"Z\"')"
            if m.group(1) == "Y-%m-%dT%H:%M:%SZ"
            else "now()"
        ),
        stmt,
    )
    # julianday(x) -> extract(epoch from x)/86400 + 2440587.5 (single-arg
    # form only; callers needing strftime-style args translate explicitly).
    stmt = re.sub(
        r"julianday\s*\(\s*([^()]+?)\s*\)",
        r"extract(epoch from \1)/86400.0 + 2440587.5",
        stmt,
        flags=re.IGNORECASE,
    )
    stmt = _INTEGER_PK_RE.sub(
        "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", stmt
    )
    # INSERT OR REPLACE/IGNORE + REPLACE INTO -> ON CONFLICT form.
    m = _INSERT_OR_RE.match(stmt)
    mode = None
    if m:
        mode = m.group(1).upper()
        stmt = re.sub(r"^\s*INSERT\s+OR\s+(REPLACE|IGNORE)\s+INTO", "INSERT INTO", stmt, flags=re.IGNORECASE)
    elif _REPLACE_INTO_RE.match(stmt):
        mode = "REPLACE"
        stmt = re.sub(r"^\s*REPLACE\s+INTO", "INSERT INTO", stmt, flags=re.IGNORECASE)
    if mode:
        stmt = _append_conflict_clause(stmt, mode, pk_resolver)
    # placeholder translation: escape stray % then ? -> %s
    stmt = re.sub(r"%(?![sbt])", "%%", stmt).replace("?", "%s")
    if mode is None:
        with _translate_lock:
            _translate_cache[statement] = stmt
            _translate_cache.move_to_end(statement)
            while len(_translate_cache) > _TRANSLATE_CACHE_MAX:
                _translate_cache.popitem(last=False)
    return stmt


def _append_conflict_clause(stmt: str, mode: str, pk_resolver: Any = None) -> str:
    """Append an ON CONFLICT clause inferred from the column list."""
    m = re.match(
        r"INSERT\s+INTO\s+([^\s(]+)\s*\(([^)]*)\)\s*VALUES\s*\(",
        stmt,
        re.IGNORECASE,
    )
    if not m:
        # INSERT INTO t SELECT ... / DEFAULT VALUES — degrade to DO NOTHING
        return stmt + " ON CONFLICT DO NOTHING" if mode == "IGNORE" else stmt
    table, columns = m.group(1), [c.strip() for c in m.group(2).split(",")]
    if mode == "IGNORE":
        return stmt + " ON CONFLICT DO NOTHING"
    if len(columns) < 2:
        return stmt + " ON CONFLICT DO NOTHING"
    # REPLACE / OR REPLACE: upsert on the table's real primary key.
    # Composite keys are resolved through the connection's PK map; when no
    # resolver is available the first column is the governed-store
    # convention for single-column primary keys.
    bare = table.strip('"').split(".")[-1]
    pk_cols = pk_resolver(bare) if pk_resolver is not None else None
    if pk_cols is None:
        pk_cols = [columns[0]]
    updates = ", ".join(
        f"{c} = EXCLUDED.{c}" for c in columns if c not in pk_cols
    )
    target = ", ".join(pk_cols)
    if not updates:
        return stmt + f" ON CONFLICT ({target}) DO NOTHING"
    return stmt + f" ON CONFLICT ({target}) DO UPDATE SET {updates}"  # sql-ok: identifiers derive from parsed INSERT column list / PK metadata, values parameterized


